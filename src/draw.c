typedef enum { CMD_RECT, CMD_PILL, CMD_TEXT } cmd_kind_t;

typedef struct {
    cmd_kind_t kind;
    int32_t x, y, w, h;
    ovl_color_t color;
    char text[DRAW_TEXT_MAX];
} cmd_t;

static cmd_t g_cmds[DRAW_MAX_CMDS];
static size_t g_count = 0;

static struct {
    uint32_t *base;
    int32_t w, h, pitch;
    uint32_t fmt;
    int32_t tiled;
    int32_t tiles_per_row;
    bool ok;
} g_s;

static uint8_t g_mort[64];
static bool g_mort_ready = false;

static void mort_init(void) {
    for (int y = 0; y < 8; y++) {
        for (int x = 0; x < 8; x++) {
            g_mort[(y << 3) | x] = (uint8_t)((x & 1) | ((y & 1) << 1) | (((x >> 1) & 1) << 2) |
                                             (((y >> 1) & 1) << 3) | (((x >> 2) & 1) << 4) |
                                             (((y >> 2) & 1) << 5));
        }
    }
    g_mort_ready = true;
}

void draw_set_surface(void *base, int32_t w, int32_t h, int32_t pitch_px,
                      uint32_t fmt, int32_t tiled) {
    if (!g_mort_ready) {
        mort_init();
    }
    g_s.base = (uint32_t *)base;
    g_s.w = w;
    g_s.h = h;
    g_s.pitch = pitch_px > 0 ? pitch_px : w;
    g_s.fmt = fmt;
    g_s.tiled = tiled;
    g_s.tiles_per_row = (g_s.pitch + 7) >> 3;
    g_s.ok = base != NULL && w > 0 && h > 0 &&
             (fmt == OVL_FMT_A8R8G8B8_SRGB || fmt == OVL_FMT_A8B8G8R8_SRGB ||
              fmt == OVL_FMT_A2R10G10B10 || fmt == OVL_FMT_A2R10G10B10_SRGB);
}

bool draw_surface_ok(void) {
    return g_s.ok;
}

static uint32_t pack(ovl_color_t c) {
    switch (g_s.fmt) {
    case OVL_FMT_A8R8G8B8_SRGB:
        return 0xFF000000u | ((uint32_t)c.r << 16) | ((uint32_t)c.g << 8) | c.b;
    case OVL_FMT_A8B8G8R8_SRGB:
        return 0xFF000000u | ((uint32_t)c.b << 16) | ((uint32_t)c.g << 8) | c.r;
    default: {
        uint32_t r = ((uint32_t)c.r << 2) | (c.r >> 6);
        uint32_t g = ((uint32_t)c.g << 2) | (c.g >> 6);
        uint32_t b = ((uint32_t)c.b << 2) | (c.b >> 6);
        return (3u << 30) | (r << 20) | (g << 10) | b;
    }
    }
}

static inline void put(int32_t x, int32_t y, uint32_t px) {
    if (g_s.tiled) {
        size_t off = ((size_t)(y >> 3) * (size_t)g_s.tiles_per_row + (size_t)(x >> 3)) * 64u +
                     g_mort[((y & 7) << 3) | (x & 7)];
        g_s.base[off] = px;
    } else {
        g_s.base[(size_t)y * (size_t)g_s.pitch + (size_t)x] = px;
    }
}

static void fill(int32_t x, int32_t y, int32_t w, int32_t h, uint32_t px) {
    int32_t x1 = x + w;
    int32_t y1 = y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (x1 > g_s.w) x1 = g_s.w;
    if (y1 > g_s.h) y1 = g_s.h;
    for (int32_t yy = y; yy < y1; yy++) {
        if (!g_s.tiled) {
            uint32_t *row = g_s.base + (size_t)yy * (size_t)g_s.pitch;
            for (int32_t xx = x; xx < x1; xx++) {
                row[xx] = px;
            }
        } else {
            for (int32_t xx = x; xx < x1; xx++) {
                put(xx, yy, px);
            }
        }
    }
}

static void push(const cmd_t *c) {
    if (g_count < DRAW_MAX_CMDS) {
        g_cmds[g_count++] = *c;
    }
}

void draw_begin(void) {
    g_count = 0;
}

void draw_rect(int32_t x, int32_t y, int32_t w, int32_t h, ovl_color_t color) {
    if (w <= 0 || h <= 0) {
        return;
    }
    cmd_t c;
    c.kind = CMD_RECT;
    c.x = x; c.y = y; c.w = w; c.h = h;
    c.color = color;
    c.text[0] = '\0';
    push(&c);
}

void draw_pill(int32_t x, int32_t y, int32_t w, int32_t h, ovl_color_t color) {
    if (w <= 0 || h <= 0) {
        return;
    }
    cmd_t c;
    c.kind = CMD_PILL;
    c.x = x; c.y = y; c.w = w; c.h = h;
    c.color = color;
    c.text[0] = '\0';
    push(&c);
}

void draw_text(int32_t x, int32_t y, const char *text, ovl_color_t color, int32_t scale) {
    if (text == NULL || scale < 1) {
        return;
    }
    cmd_t c;
    c.kind = CMD_TEXT;
    c.x = x; c.y = y; c.w = scale; c.h = 0;
    c.color = color;
    ovl_copy(c.text, DRAW_TEXT_MAX, text);
    push(&c);
}

int32_t draw_text_width(const char *text, int32_t scale) {
    return (int32_t)ovl_strlen(text) * DRAW_GLYPH_W * scale;
}

static void raster_text(const cmd_t *c, uint32_t px) {
    int32_t s = c->w;
    int32_t x = c->x;
    for (const char *p = c->text; *p != '\0'; p++) {
        uint8_t ch = (uint8_t)*p;
        if (ch >= 32 && ch <= 126) {
            const uint8_t *g = g_font[ch - 32];
            for (int row = 0; row < 8; row++) {
                uint8_t bits = g[row];
                int col = 0;
                while (col < 8) {
                    if (bits & (1u << col)) {
                        int run = 1;
                        while (col + run < 8 && (bits & (1u << (col + run)))) {
                            run++;
                        }
                        fill(x + col * s, c->y + row * s, run * s, s, px);
                        col += run;
                    } else {
                        col++;
                    }
                }
            }
        }
        x += DRAW_GLYPH_W * s;
    }
}

void draw_flush(void) {
    if (g_s.ok) {
        for (size_t i = 0; i < g_count; i++) {
            const cmd_t *c = &g_cmds[i];
            uint32_t px = pack(c->color);
            if (c->kind == CMD_RECT) {
                fill(c->x, c->y, c->w, c->h, px);
            } else if (c->kind == CMD_PILL) {
                int32_t r = (c->h < c->w ? c->h : c->w) / 3;
                if (r < 1) {
                    fill(c->x, c->y, c->w, c->h, px);
                } else {
                    fill(c->x + r, c->y, c->w - 2 * r, c->h, px);
                    fill(c->x + r / 2, c->y + r / 2, c->w - r, c->h - r, px);
                    fill(c->x, c->y + r, c->w, c->h - 2 * r, px);
                }
            } else {
                raster_text(c, px);
            }
        }
    }
    g_count = 0;
}
